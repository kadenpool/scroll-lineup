"""Write the day-4 results page from a finished run's out/ folder (generated; never edit the output by hand).

  python3 results_day4_md.py <day-4 run dir with out/results.json> <day-1 results.json> <output .md>

Everything comes from the run's results.json and summary.md; the readout is recomputed by read_day4.py and must agree
with the job's, or the page says so at the top. The reader's full output, with the margins and the leave-one-target-out
results that amendment 3 reports, is at the end.
"""
import json, os, subprocess, sys

run, day1, dst = sys.argv[1].rstrip("/"), sys.argv[2], sys.argv[3]
OUT = f"{run}/out" if os.path.exists(f"{run}/out/results.json") else run   # a run folder, or a published day*/run/
R = json.load(open(f"{OUT}/results.json"))
J, STR = R["jobs"], sorted(float(s) for s in R["strengths"])
HERE = os.path.dirname(os.path.abspath(__file__))
reader = subprocess.run([sys.executable, f"{HERE}/read_day4.py", run, day1], capture_output=True, text=True).stdout
agree = "Job readout vs recomputed here: AGREE" in reader
ARM_NAME = {"a": "arm A, 9.362 um (primary)", "b": "arm B, 8.64 um"}
targets = {a: sorted(n.split("__")[0] for n, j in J.items() if j["kind"] == "clean" and j.get("arm") == a) for a in "ab"}
smoke = len(targets["a"]) == 1
L = [f"# Day 4 results: the floor on PHerc0483B, at two scales{' (SMOKE RUN: one target per arm; numbers not used)' if smoke else ''}",
     "", "Generated by `results_day4_md.py` from the run's own output; do not edit by hand.", ""]
if not agree:
    L += ["**WARNING: the readout recomputed by read_day4.py does not agree with the job's. Read nothing below until "
          "this is resolved.**", ""]
ins = R.get("inputs", {}).get("sha256", {})
parts = R.get("complete_by_part", {})
L += [f"- Code: `{R['script_version']}`",
      f"- Ran {R['started_utc']} to {R.get('finished_utc')} on {R.get('gpus')} GPU(s); status `{R['status']}`; "
      f"errors: {', '.join(sorted(R['errors'])) or 'none'}",
      "- Inputs (sha256, as pinned): " + ", ".join(f"{k} `{v[:16]}`" for k, v in sorted(ins.items())),
      "- Checkpoints: " + "; ".join(f"{t} revision `{c.get('hf_revision', '')[:12]}` sha256 `{c.get('sha256', '')[:16]}`"
                                     for t, c in R.get("checkpoints", {}).items()),
      f"- Jobs: {len(J)} ({len(targets['a'])} targets in each arm, "
      f"{sum(1 for j in J.values() if j['kind'] == 'reference')} references, "
      f"{sum(1 for j in J.values() if j['kind'] == 'scale_reference')} scale references, "
      f"{sum(1 for j in J.values() if j['kind'] == 'whole')} whole surfaces)",
      "- Every job scored in both directions, by part: " + "; ".join(
          f"{p} " + ", ".join(f"{t} {'yes' if ok else 'NO'}" for t, ok in v.items()) for p, v in parts.items()), "",
      "## Readout (PREREG amendment 3)", "", open(f"{OUT}/summary.md").read().strip(), "",
      f"Recomputed apart from the job by `read_day4.py`: {'AGREE' if agree else 'DIFFER'}.", ""]
fmt = lambda f: "above 1" if f is None else "%.3f" % f
iqr = lambda q: "; ".join("s%s %.3f to %.3f" % (s_, v[0], v[1]) for s_, v in q.items())
for arm in ("a", "b"):
    for tag, g in R.get("readout", {}).get(arm, {}).items():
        d = g["primary_direction"]
        det = fmt(g["detection_floor"]) if g["read"] else "not read"
        clr = fmt(g["clear_floor"]) if g["read"] else "not read"
        L += [f"## {ARM_NAME[arm]}: {tag}, primary direction {d}", "",
              f"- Control: largest change of a reference AUC from day 1: {g['control_largest_reference_change']:.4f} "
              f"({'within 0.01' if g['control_ok'] else 'MORE than 0.01: not read'})",
              f"- Sham interquartile ranges: PHerc0483B {iqr(g['sham_interquartile'])} | PHerc0139 "
              f"{iqr(g['xsham_interquartile'])}",
              f"- Checks: {'pass' if g['checks_ok'] else 'FAIL'}; detection floor {det}; clear floor {clr}", ""]
        for dd in (d, "reverse" if d == "forward" else "forward"):
            rows = [f"AUC per target, {dd}{' (the primary direction, used by the readout)' if dd == d else ' (reported, not used)'}:",
                    "", "| target | surface | donor | clean | " + " | ".join(f"s{s:g}" for s in STR) + " | " +
                    " | ".join(f"sham s{s:g}" for s in STR) + " | " + " | ".join(f"PHerc0139 sham s{s:g}" for s in STR) + " |",
                    "|---|---|---|---|" + "---|" * (3 * len(STR))]
            for t in targets[arm]:
                j = J[f"{t}__clean"]
                a = lambda k: J[k]["auc"][tag][dd]
                rows.append(f"| {t} | {j['surface']} | {j['donor']} | {a(f'{t}__clean'):.3f} | " +
                            " | ".join(f"{a(f'{t}__swap__s{s:g}'):.3f}" for s in STR) + " | " +
                            " | ".join(f"{a(f'{t}__swap__sham{s:g}'):.3f}" for s in STR) + " | " +
                            " | ".join(f"{a(f'{t}__swap__xsham{s:g}'):.3f}" for s in STR) + " |")
            L += rows + [""]
L += ["## Arm A minus arm B (descriptive; no threshold)", ""]
for tag, dif in R.get("difference", {}).items():
    if not dif.get("read"):
        L += [f"- {tag}: not given (arm A {'read' if dif.get('read_a') else 'not read'}, arm B "
              f"{'read' if dif.get('read_b') else 'not read'})"]
        continue
    L += [f"- {tag}, {dif['primary_direction']}: median over targets " +
          ", ".join(f"s{float(s):g} {v:+.3f}" for s, v in dif["median_a_minus_b"].items()),
          "  per target at s1: " + ", ".join(f"{t} {row.get('1.0', row.get(1.0, float('nan'))):+.3f}"
                                             for t, row in dif["a_minus_b_by_target"].items())]
L += ["", "## Scale references (arm B: the six day-1 donor windows read at 8.64 um; not a gate)", ""]
for tag, sr in R.get("scale_references", {}).items():
    L += [f"- {tag}, {sr['primary_direction']}: median AUC {sr['median_auc_a']:.3f} at 9.362 um, {sr['median_auc_b']:.3f} "
          f"at 8.64 um, median A minus B {sr['median_a_minus_b']:+.3f}"]
L += ["", "## Each donor's ink contrast at its sheet layer, at 9.362 um and after resampling to 8.64 um (arm B)", "",
      "In texture standard deviations, as day 1 measures it; the ink area ratio is the letters' physical area at 8.64 um "
      "over their area at 9.362 um.", "",
      "| donor | segment | at 9.362 um | at 8.64 um | ink area ratio |", "|---|---|---|---|---|"]
for i, dn in enumerate(R.get("donors", [])):
    L.append(f"| {i} | {dn['seg']} | {dn['ink_contrast_at_sheet']:+.3f} | {dn.get('b_ink_contrast_at_sheet', float('nan')):+.3f} | "
             f"{dn.get('b_ink_area_ratio_physical', float('nan')):.4f} |")
L += ["", "## Texture scale and clipping, per target", "",
      "k scales each donor's letters to the target's texture (PREREG section 5), computed in each arm on that arm's "
      "residual; the shams use their own k. The clipped share is the largest, over the target's planted and sham jobs, "
      "of voxels pushed past 0 or 255.", "",
      "| arm | target | surface | donor | k | k, PHerc0483B sham | k, PHerc0139 sham | largest clipped share |",
      "|---|---|---|---|---|---|---|---|"]
for arm in ("a", "b"):
    for t in targets[arm]:
        j = J[f"{t}__clean"]
        clip = max(J[m].get("clipped_share", 0.0) for m in J if m.startswith(t + "__"))
        L.append(f"| {arm.upper()} | {t} | {j['surface']} | {j['donor']} | {j['k']:.3f} | {j['k_sham']:.3f} | "
                 f"{j['k_xsham']:.3f} | {100 * clip:.2f} % |")
L += [""]
whole = [(n, j) for n, j in J.items() if j["kind"] == "whole"]
if whole:
    L += ["## The models' own output on the whole surfaces (mean map value; no letters are claimed)", "",
          "The raw maps are published as they are, with the floors above beside them (amendment 3).", "",
          "| arm | surface | " + " | ".join(f"{t} {d}" for t in R.get("checkpoints", {}) for d in ("forward", "reverse")) + " |",
          "|---|---|" + "---|" * (2 * len(R.get("checkpoints", {})))]
    for n, j in sorted(whole):
        m = j.get("mean", {})
        L.append(f"| {j.get('arm', '').upper()} | {j['surface']} | " + " | ".join(
            f"{m.get(t, {}).get(d, float('nan')):.4f}" for t in R.get("checkpoints", {}) for d in ("forward", "reverse")) + " |")
    L += [""]
L += ["## The reader's full output (with each result's margin and the leave-one-target-out results)", "", "```",
      reader.strip(), "```", ""]
open(dst, "w").write("\n".join(L))
print(f"wrote {dst}: {len(L)} lines; readout {'AGREE' if agree else 'DIFFER'}")

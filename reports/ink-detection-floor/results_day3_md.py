"""Write the day-3 results page from a finished run's out/ folder (generated; never edit the output by hand).

  python3 results_day3_md.py <day-3 run dir with out/results.json> <day-1 results.json> <output .md>

Everything comes from the run's results.json and summary.md; the readout is recomputed by read_day3.py and must agree
with the kernel's, or the page says so at the top.
"""
import json, os, subprocess, sys

run, day1, dst = sys.argv[1].rstrip("/"), sys.argv[2], sys.argv[3]
OUT = f"{run}/out" if os.path.exists(f"{run}/out/results.json") else run   # a run folder, or a published day*/run/
R = json.load(open(f"{OUT}/results.json"))
J, STR = R["jobs"], sorted(float(s) for s in R["strengths"])
HERE = os.path.dirname(os.path.abspath(__file__))
reader = subprocess.run([sys.executable, f"{HERE}/read_day3.py", run, day1], capture_output=True, text=True).stdout
agree = "AGREE" in reader and "DIFFER" not in reader
n_t = sum(1 for j in J.values() if j["kind"] == "clean")
L = [f"# Day 3 results: the floor on PHerc0846B{' (SMOKE RUN: one target; numbers not used)' if n_t == 1 else ''}", "",
     "Generated by `results_day3_md.py` from the run's own output; do not edit by hand.", ""]
if not agree:
    L += ["**WARNING: the readout recomputed by read_day3.py does not agree with the kernel's. Read nothing below until "
          "this is resolved.**", ""]
ins = R.get("inputs", {}).get("sha256", {})
L += [f"- Code: `{R['script_version']}`",
      f"- Ran {R['started_utc']} to {R.get('finished_utc')} on {R.get('gpus')} GPU(s); status `{R['status']}`; "
      f"errors: {', '.join(sorted(R['errors'])) or 'none'}",
      "- Inputs (sha256, as pinned): " + ", ".join(f"{k} `{v[:16]}`" for k, v in sorted(ins.items())),
      "- Checkpoints: " + "; ".join(f"{t} revision `{c.get('hf_revision', '')[:12]}` sha256 `{c.get('sha256', '')[:16]}`"
                                     for t, c in R.get("checkpoints", {}).items()),
      f"- Jobs: {len(J)} ({n_t} targets, {sum(1 for j in J.values() if j['kind'] == 'whole')} whole surfaces); every "
      "scored job in both directions: " + ", ".join(f"{t} {'yes' if ok else 'NO'}" for t, ok in R.get("complete", {}).items()), "",
      "## Readout (PREREG amendment 1)", "", open(f"{OUT}/summary.md").read().strip(), "",
      f"Recomputed apart from the kernel by `read_day3.py`: {'AGREE' if agree else 'DIFFER'}.", ""]
for tag, g in R.get("readout", {}).items():
    d = g["primary_direction"]
    fmt = lambda f: "above 1" if f is None else "%.3f" % f
    det = fmt(g["detection_floor"]) if g["read"] else "not read"
    clr = fmt(g["clear_floor"]) if g["read"] else "not read"
    iqr = lambda q: "; ".join("s%s %.3f to %.3f" % (s_, v[0], v[1]) for s_, v in q.items())
    change = g["control_largest_reference_change"]
    L += [f"## {tag}, primary direction {d}", "",
          f"- Control: largest change of a reference AUC from day 1: {change:.4f} "
          f"({'within 0.01' if g['control_ok'] else 'MORE than 0.01: not read'})",
          f"- Sham interquartile ranges: PHerc0846B {iqr(g['sham_interquartile'])} | PHerc0139 {iqr(g['xsham_interquartile'])}",
          f"- Checks: {'pass' if g['checks_ok'] else 'FAIL'}; detection floor {det}; clear floor {clr}", ""]
    for dd in (d, "reverse" if d == "forward" else "forward"):
        rows = [f"AUC per target, {dd}{' (the primary direction, used by the readout)' if dd == d else ' (reported, not used)'}:",
                "", "| target | surface | donor | clean | " + " | ".join(f"s{s:g}" for s in STR) + " | " +
                " | ".join(f"sham s{s:g}" for s in STR) + " | " + " | ".join(f"PHerc0139 sham s{s:g}" for s in STR) + " |",
                "|---|---|---|---|" + "---|" * (3 * len(STR))]
        for n, j in J.items():
            if j["kind"] != "clean":
                continue
            t = n.split("__")[0]
            a = lambda k: J[k]["auc"][tag][dd]
            rows.append(f"| {t} | {j['surface']} | {j['donor']} | {a(n):.3f} | " +
                        " | ".join(f"{a(f'{t}__swap__s{s:g}'):.3f}" for s in STR) + " | " +
                        " | ".join(f"{a(f'{t}__swap__sham{s:g}'):.3f}" for s in STR) + " | " +
                        " | ".join(f"{a(f'{t}__swap__xsham{s:g}'):.3f}" for s in STR) + " |")
        L += rows + [""]
L += ["## Texture scale and clipping, per target", "",
      "k scales each donor's letters to the target's texture (PREREG section 5); the shams use their own k. The clipped "
      "share is the largest, over the target's planted and sham jobs, of voxels pushed past 0 or 255.", "",
      "| target | surface | donor | k | k, PHerc0846B sham | k, PHerc0139 sham | largest clipped share |", "|---|---|---|---|---|---|---|"]
for n, j in J.items():
    if j["kind"] != "clean":
        continue
    t = n.split("__")[0]
    clip = max(J[m].get("clipped_share", 0.0) for m in J if m.startswith(t + "__"))
    L.append(f"| {t} | {j['surface']} | {j['donor']} | {j['k']:.3f} | {j['k_sham']:.3f} | {j['k_xsham']:.3f} | {100 * clip:.2f} % |")
L += [""]
whole = [(n, j) for n, j in J.items() if j["kind"] == "whole"]
if whole:
    fl = lambda g: (("detection floor " + ("above 1" if g["detection_floor"] is None else "%.3f" % g["detection_floor"])
                     + " of full strength") if g["read"] else
                    "no floor (" + ("its control moved" if not g["control_ok"] else "its checks failed") + ")")
    L += ["## The models' own output on the whole surfaces (mean map value; no letters are claimed)", "",
          "Shown with the floor beside it (amendment 1): " + "; ".join(f"{t}, {fl(g)}" for t, g in R.get("readout", {}).items())
          + ". The figure `day3/whole_surfaces.png` shows each surface's CT beside both checkpoints' forward maps; the raw "
          "maps are in the data release linked from the README.", "",
          "| surface | " + " | ".join(f"{t} {d}" for t in R.get("checkpoints", {}) for d in ("forward", "reverse")) + " |",
          "|---|" + "---|" * (2 * len(R.get("checkpoints", {})))]
    for n, j in whole:
        m = j.get("mean", {})
        L.append(f"| {j['surface']} | " + " | ".join(f"{m.get(t, {}).get(d, float('nan')):.4f}"
                                                     for t in R.get("checkpoints", {}) for d in ("forward", "reverse")) + " |")
    L += [""]
L += ["## The reader's full output", "", "```", reader.strip(), "```", ""]
open(dst, "w").write("\n".join(L))
print(f"wrote {dst}: {len(L)} lines; readout {'AGREE' if agree else 'DIFFER'}")

"""Write the day-1 results page from a finished run's out/ folder (generated; never edit the output by hand).

  python3 results_md.py <run dir with out/results.json> <output .md>

Everything printed comes from results.json, the kept maps and masks.npz; the gates are recomputed by read_day1.py's
rules and must agree with the kernel's, or the page says so at the top.
"""
import glob, json, os, statistics, subprocess, sys
import numpy as np

run, dst = sys.argv[1].rstrip("/"), sys.argv[2]
OUT = f"{run}/out" if os.path.exists(f"{run}/out/results.json") else run   # a run folder, or a published day*/run/
R = json.load(open(f"{OUT}/results.json"))
J, STR = R["jobs"], [float(s) for s in R["strengths"]]
HERE = os.path.dirname(os.path.abspath(__file__))
reader = subprocess.run([sys.executable, f"{HERE}/read_day1.py", run], capture_output=True, text=True).stdout
agree = "AGREE" in reader and "DIFFER" not in reader
med = lambda xs: statistics.median(xs) if xs else float("nan")
n_t = sum(1 for j in J.values() if j["kind"] == "clean")
L = [f"# Day 1 results{' (SMOKE RUN: one target; numbers not used)' if n_t == 1 else ''}", "",
     "Generated by `results_md.py` from the run's own output; do not edit by hand.", ""]
if not agree:
    L += ["**WARNING: the gates recomputed by read_day1.py do not agree with the kernel's. Read nothing below until "
          "this is resolved.**", ""]
L += [f"- Code: `{R['script_version']}`",
      f"- Ran {R['started_utc']} to {R.get('finished_utc')} on {R.get('gpus')} GPU(s); status `{R['status']}`; "
      f"errors: {', '.join(sorted(R['errors'])) or 'none'}",
      f"- Inputs (sha256): windows.json `{R['inputs']['sha256']['windows.json']}`, masks.npz "
      f"`{R['inputs']['sha256']['masks.npz']}`",
      "- Checkpoints: " + "; ".join(f"{t} revision `{c.get('hf_revision', '')[:12]}` sha256 `{c.get('sha256', '')[:16]}`"
                                     for t, c in R.get("checkpoints", {}).items()),
      f"- Jobs: {len(J)} ({sum(1 for j in J.values() if j['kind'] == 'reference')} references, {n_t} targets); "
      f"every job scored in both directions: {R.get('complete')}", "",
      "## Gates (PREREG section 7)", "", open(f"{OUT}/summary.md").read().strip(), "",
      f"Recomputed apart from the kernel by `read_day1.py`: {'AGREE' if agree else 'DIFFER'}.", ""]
mk = np.load(sorted(glob.glob(f"{HERE}/day1/masks.npz"))[0])
for tag in R.get("checkpoints", {}):
    g0 = next((g for k, g in R.get("gates", {}).items() if k.startswith(tag)), None)
    if not g0:
        continue
    d = g0["primary_direction"]
    a = {n: J[n]["auc"][tag][d] for n in J}
    L += [f"## {tag}, primary direction {d}", ""]
    refs = [n for n in J if J[n]["kind"] == "reference"]
    L += ["References (the donors' letters in place): " + ", ".join(f"{J[n]['seg']} #{J[n]['donor']} {a[n]:.3f}" for n in refs), ""]
    L += ["| target | donor | clean | transplant | " + " | ".join(f"{m} s{s:g}" for m in R["plants"] for s in STR) +
          " | " + " | ".join(f"{m} sham s{s:g}" for m in R["plants"] for s in STR) + " |",
          "|---|---|---|---|" + "---|" * (2 * len(R["plants"]) * len(STR))]
    for n in J:
        if J[n]["kind"] != "clean":
            continue
        t = n.split("__")[0]
        cells = [f"{a[f'{t}__{m}__s{s:g}']:.3f}" for m in R["plants"] for s in STR] + \
                [f"{a[f'{t}__{m}__sham{s:g}']:.3f}" for m in R["plants"] for s in STR]
        L.append(f"| {t} | {J[n]['donor']} | {a[n]:.3f} | {a[f'{t}__transplant']:.3f} | " + " | ".join(cells) + " |")
    L += [""]
    for k, g in R["gates"].items():
        if not k.startswith(tag):
            continue
        iqr = "; ".join(f"s{s} {v[0]:.3f} to {v[1]:.3f}" for s, v in g["sham_interquartile"].items())
        L += [f"- {k.split('/')[1]}: planted minus transplant at s = 1 {g['planted_minus_transplant_at_1']:+.3f}; planted "
              f"minus reference {g['planted_minus_reference_at_1']:+.3f}; context gap "
              f"{g['context_gap_transplant_minus_reference']:+.3f}; sham interquartile ranges {iqr}"]
    L += [""]
L += ["## Beside G1: letters only (PREREG section 2; not a gate)", "",
      "```", "\n".join(l for l in reader.splitlines() if "positives only" in l) or "(no kept maps found)", "```", "",
      "## Clipping (PREREG section 5)", "", "```",
      "\n".join(l.strip() for l in reader.splitlines() if "clipped share" in l), "```", "",
      "## The reader's full output", "", "```", reader.strip(), "```", ""]
open(dst, "w").write("\n".join(L))
print(f"wrote {dst}: {len(L)} lines; gates {'AGREE' if agree else 'DIFFER'}")
